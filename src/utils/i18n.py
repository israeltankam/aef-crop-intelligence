def get_language() -> str:
    """Return the active UI language, defaulting safely to English."""
    if st is None:
        return DEFAULT_LANGUAGE
    lang = st.session_state.get(LANG_SESSION_KEY, DEFAULT_LANGUAGE)
    return lang if lang in SUPPORTED_LANGUAGES else DEFAULT_LANGUAGE


def set_language(lang: str) -> None:
    """Persist a language choice in Streamlit session state."""
    if st is not None and lang in SUPPORTED_LANGUAGES:
        st.session_state[LANG_SESSION_KEY] = lang


def tr(text: str, **kwargs: Any) -> str:
    """Translate a legacy literal UI string while preserving English fallback."""
    lang = get_language()
    translated = LITERAL_TRANSLATIONS.get(lang, {}).get(text, text)
    return translated.format(**kwargs) if kwargs else translated


def t(key: str, **kwargs: Any) -> str:
    """Translate a key and apply optional Python format placeholders."""
    lang = get_language()
    text = TRANSLATIONS.get(lang, {}).get(key) or TRANSLATIONS[DEFAULT_LANGUAGE].get(key) or key
    return text.format(**kwargs) if kwargs else text


def language_selector(location: str = "sidebar", key: str = "aef_language_selector") -> None:
    """Render a visible French/English selector and persist the choice.

    On the login screen the sidebar is collapsed, so the selector must be drawn
    in the main page. Once authenticated, the same control can live in the
    sidebar and the selected language continues to drive every translated key.
    """
    if st is None:
        return
    container = st.sidebar if location == "sidebar" else st
    current = get_language()
    codes = list(SUPPORTED_LANGUAGES.keys())
    labels = [SUPPORTED_LANGUAGES[c] for c in codes]
    idx = codes.index(current) if current in codes else 0
    selected_label = container.radio(
        t("language.label"),
        labels,
        index=idx,
        key=key,
        horizontal=True,
    )
    set_language(codes[labels.index(selected_label)])
